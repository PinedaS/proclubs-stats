alter table public.matches add column opponent_skill_rating integer;

comment on column public.matches.opponent_skill_rating is
  'skillRating del rival (clubs/overallStats) cuando el colector vio el partido por primera vez.';

-- Seguridad de member_snapshots: mismo criterio que el resto.
alter table public.member_snapshots enable row level security;
create policy member_snapshots_read on public.member_snapshots for select to anon, authenticated using (true);
revoke all on public.member_snapshots from anon, authenticated;
grant select (club_id, member_name, snapshot_date, captured_at, pro_overall, games_played, goals, assists,
              win_rate, pass_success_rate, shot_success_rate, tackle_success_rate, passes_made, tackles_made,
              clean_sheets_def, clean_sheets_gk, rating_avg, man_of_the_match, red_cards, favorite_position,
              pro_name, pro_height)
  on public.member_snapshots to anon, authenticated;
grant select, insert, update, delete on public.member_snapshots to service_role;

-- -----------------------------------------------------------------------------
-- 3. Último estado de cada miembro + conciliación aproximada:
--    partidos que EA le sumó desde la primera foto vs. partidos que capturamos.
-- -----------------------------------------------------------------------------
create view public.v_member_latest
with (security_invoker = true)
as
with latest as (
  select distinct on (s.club_id, s.member_name)
         s.club_id, s.member_name, s.snapshot_date, s.pro_overall, s.games_played, s.goals, s.assists,
         s.win_rate, s.pass_success_rate, s.shot_success_rate, s.tackle_success_rate, s.passes_made,
         s.tackles_made, s.clean_sheets_def, s.clean_sheets_gk, s.rating_avg, s.man_of_the_match,
         s.red_cards, s.favorite_position, s.pro_name, s.pro_height
  from public.member_snapshots s
  order by s.club_id, s.member_name, s.snapshot_date desc
),
first_snap as (
  select distinct on (s.club_id, s.member_name)
         s.club_id, s.member_name, s.snapshot_date as first_date, s.captured_at as first_captured_at,
         s.games_played as first_games, s.pro_overall as first_overall
  from public.member_snapshots s
  order by s.club_id, s.member_name, s.snapshot_date asc
)
select
  l.*,
  f.first_date,
  f.first_overall,
  l.games_played - f.first_games as ea_games_since_first,
  (select count(distinct st.match_id)
     from public.player_match_stats st
     join public.matches  m on m.match_id  = st.match_id
     join public.accounts a on a.player_id = st.player_id
    where m.club_id = l.club_id
      and lower(a.last_known_name) = lower(l.member_name)
      and m.played_at >= f.first_captured_at) as captured_since_first,
  (select a.person_id from public.accounts a
    where lower(a.last_known_name) = lower(l.member_name)
    order by a.last_seen_at desc limit 1) as person_id
from latest l
join first_snap f on f.club_id = l.club_id and f.member_name = l.member_name;

revoke insert, update, delete, truncate, references, trigger on public.v_member_latest from anon, authenticated;
grant select on public.v_member_latest to anon, authenticated, service_role;

-- -----------------------------------------------------------------------------
-- 4. Vista por partido: nuevas columnas al final.
-- -----------------------------------------------------------------------------
create or replace view public.v_player_match_stats
with (security_invoker = true)
as
select
  s.match_id, m.club_id, c.season, m.match_type, m.played_at, m.outcome, m.goals_for, m.goals_against,
  m.opponent_name, a.person_id, p.display_name as person_name, s.player_id, s.playername, s.position,
  s.archetype_id, s.rating, s.goals, s.assists, s.shots, s.pass_attempts, s.passes_made, s.tackle_attempts,
  s.tackles_made, s.is_mom, s.red_cards, s.saves, s.goals_conceded, s.clean_sheets_def, s.clean_sheets_gk,
  s.seconds_played,
  public.event_sum(s.event_counts, array['174'])               as dribbles_exp,
  public.event_sum(s.event_counts, array['6'])                 as interceptions_exp,
  public.event_sum(s.event_counts, array['108', '109', '110']) as possession_won_exp,
  public.event_sum(s.event_counts, array['105', '106', '107']) as possession_lost_exp,
  public.event_sum(s.event_counts, array['265', '266'])        as aerial_duels_won_exp,
  public.event_sum(s.event_counts, array['2', '3'])            as fouls_exp,
  public.event_sum(s.event_counts, array['95', '213'])         as yellow_cards_exp,
  m.opponent_skill_rating,
  public.event_sum(s.event_counts, array['217'])               as shots_on_target_exp,
  public.event_sum(s.event_counts, array['218'])               as shots_off_target_exp,
  public.event_sum(s.event_counts, array['115'])               as second_assists_exp
from public.player_match_stats s
join public.matches  m on m.match_id  = s.match_id
join public.clubs    c on c.club_id   = m.club_id
join public.accounts a on a.player_id = s.player_id
join public.persons  p on p.person_id = a.person_id;

-- -----------------------------------------------------------------------------
-- 5. person_stats con métricas calculadas (columnas nuevas al final).
-- -----------------------------------------------------------------------------
drop view public.v_person_totals;
drop function public.person_stats(text[], timestamptz, timestamptz, text, bigint);

create function public.person_stats(
  p_match_types text[]      default null,
  p_from        timestamptz default null,
  p_to          timestamptz default null,
  p_season      text        default null,
  p_club_id     bigint      default null
)
returns table (
  person_id bigint, person_name text, main_position text, matches bigint, wins bigint, draws bigint,
  losses bigint, goals bigint, assists bigint, goal_contributions bigint, shots bigint, passes_made bigint,
  pass_attempts bigint, pass_accuracy_pct numeric, tackles_made bigint, tackle_attempts bigint,
  tackle_success_pct numeric, saves bigint, goals_conceded bigint, clean_sheets_def bigint,
  clean_sheets_gk bigint, mom_count bigint, mom_pct numeric, red_cards bigint, avg_rating numeric,
  seconds_played bigint, goals_per_match numeric, assists_per_match numeric, ga_per_match numeric,
  dribbles_exp bigint, interceptions_exp bigint, possession_won_exp bigint, possession_lost_exp bigint,
  aerial_duels_won_exp bigint, fouls_exp bigint, yellow_cards_exp bigint,
  -- Calculadas (oficiales)
  minutes_played numeric,
  goals_per90 numeric,
  assists_per90 numeric,
  ga_per90 numeric,
  shot_conversion_pct numeric,
  save_pct numeric,
  clean_sheets bigint,
  team_goals bigint,
  goal_participation_pct numeric,
  goal_diff bigint,
  club_matches bigint,
  attendance_pct numeric,
  form_rating numeric,
  rating_stddev numeric,
  avg_opponent_skill numeric,
  -- Calculadas (experimentales)
  shots_on_target_exp bigint,
  shot_accuracy_exp_pct numeric,
  second_assists_exp bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  with base as (
    select v.*
    from public.v_player_match_stats v
    where (p_match_types is null or v.match_type = any (p_match_types))
      and (p_from        is null or v.played_at >= p_from)
      and (p_to          is null or v.played_at <  p_to)
      and (p_season      is null or v.season    =  p_season)
      and (p_club_id     is null or v.club_id   =  p_club_id)
  ),
  agg as (
    select
      v.person_id,
      v.person_name,
      mode() within group (order by v.position)                                   as main_position,
      count(distinct v.match_id)                                                  as matches,
      count(distinct v.match_id) filter (where v.outcome = 'win')                 as wins,
      count(distinct v.match_id) filter (where v.outcome = 'draw')                as draws,
      count(distinct v.match_id) filter (where v.outcome = 'loss')                as losses,
      sum(v.goals)                                                                as goals,
      sum(v.assists)                                                              as assists,
      sum(v.shots)                                                                as shots,
      sum(v.passes_made)                                                          as passes_made,
      sum(v.pass_attempts)                                                        as pass_attempts,
      sum(v.tackles_made)                                                         as tackles_made,
      sum(v.tackle_attempts)                                                      as tackle_attempts,
      sum(v.saves)                                                                as saves,
      sum(v.goals_conceded)                                                       as goals_conceded,
      sum(v.clean_sheets_def)                                                     as clean_sheets_def,
      sum(v.clean_sheets_gk)                                                      as clean_sheets_gk,
      count(*) filter (where v.is_mom)                                            as mom_count,
      sum(v.red_cards)                                                            as red_cards,
      round(avg(v.rating), 2)                                                     as avg_rating,
      sum(v.seconds_played)                                                       as seconds_played,
      sum(v.dribbles_exp)                                                         as dribbles_exp,
      sum(v.interceptions_exp)                                                    as interceptions_exp,
      sum(v.possession_won_exp)                                                   as possession_won_exp,
      sum(v.possession_lost_exp)                                                  as possession_lost_exp,
      sum(v.aerial_duels_won_exp)                                                 as aerial_duels_won_exp,
      sum(v.fouls_exp)                                                            as fouls_exp,
      sum(v.yellow_cards_exp)                                                     as yellow_cards_exp,
      sum(v.saves)          filter (where v.position = 'goalkeeper')              as gk_saves,
      sum(v.goals_conceded) filter (where v.position = 'goalkeeper')              as gk_conceded,
      sum(v.shots_on_target_exp)                                                  as shots_on_target_exp,
      sum(v.shots_off_target_exp)                                                 as shots_off_target_exp,
      sum(v.second_assists_exp)                                                   as second_assists_exp
    from base v
    group by v.person_id, v.person_name
  ),
  -- Una fila por persona y partido (una persona con 2 cuentas no duplica el partido).
  person_match as (
    select b.person_id, b.match_id,
           max(b.played_at) as played_at, max(b.goals_for) as gf, max(b.goals_against) as ga,
           max(b.opponent_skill_rating) as opp_skill, avg(b.rating) as rating
    from base b
    group by b.person_id, b.match_id
  ),
  ranked as (
    select pm.*, row_number() over (partition by pm.person_id order by pm.played_at desc) as rn
    from person_match pm
  ),
  per_person as (
    select r.person_id,
           sum(r.gf)                                   as team_goals,
           sum(r.gf - r.ga)                            as goal_diff,
           avg(r.opp_skill)                            as avg_opp_skill,
           avg(r.rating) filter (where r.rn <= 5)      as form_rating,
           stddev_samp(r.rating)                       as rating_stddev
    from ranked r
    group by r.person_id
  ),
  club as (select count(distinct b.match_id) as n from base b)
  select
    a.person_id, a.person_name, a.main_position, a.matches, a.wins, a.draws, a.losses,
    a.goals, a.assists, a.goals + a.assists, a.shots, a.passes_made, a.pass_attempts,
    round(100.0 * a.passes_made  / nullif(a.pass_attempts, 0), 1),
    a.tackles_made, a.tackle_attempts,
    round(100.0 * a.tackles_made / nullif(a.tackle_attempts, 0), 1),
    a.saves, a.goals_conceded, a.clean_sheets_def, a.clean_sheets_gk, a.mom_count,
    round(100.0 * a.mom_count / a.matches, 1),
    a.red_cards, a.avg_rating, a.seconds_played,
    round(a.goals::numeric / a.matches, 2),
    round(a.assists::numeric / a.matches, 2),
    round((a.goals + a.assists)::numeric / a.matches, 2),
    a.dribbles_exp, a.interceptions_exp, a.possession_won_exp, a.possession_lost_exp,
    a.aerial_duels_won_exp, a.fouls_exp, a.yellow_cards_exp,
    round(a.seconds_played / 60.0, 0),
    round(a.goals * 5400.0 / nullif(a.seconds_played, 0), 2),
    round(a.assists * 5400.0 / nullif(a.seconds_played, 0), 2),
    round((a.goals + a.assists) * 5400.0 / nullif(a.seconds_played, 0), 2),
    round(100.0 * a.goals / nullif(a.shots, 0), 1),
    round(100.0 * a.gk_saves / nullif(a.gk_saves + a.gk_conceded, 0), 1),
    a.clean_sheets_def + a.clean_sheets_gk,
    p.team_goals,
    round(100.0 * (a.goals + a.assists) / nullif(p.team_goals, 0), 1),
    p.goal_diff,
    c.n,
    round(100.0 * a.matches / nullif(c.n, 0), 1),
    round(p.form_rating, 2),
    round(p.rating_stddev, 2),
    round(p.avg_opp_skill, 0),
    a.shots_on_target_exp,
    round(100.0 * a.shots_on_target_exp / nullif(a.shots_on_target_exp + a.shots_off_target_exp, 0), 1),
    a.second_assists_exp
  from agg a
  join per_person p on p.person_id = a.person_id
  cross join club c
$$;

create view public.v_person_totals
with (security_invoker = true)
as
select * from public.person_stats();

revoke insert, update, delete, truncate, references, trigger on public.v_person_totals from anon, authenticated;
grant select on public.v_person_totals to anon, authenticated, service_role;
grant execute on function public.person_stats(text[], timestamptz, timestamptz, text, bigint)
  to anon, authenticated, service_role;
