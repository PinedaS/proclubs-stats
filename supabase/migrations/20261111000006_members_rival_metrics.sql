-- -----------------------------------------------------------------------------
-- 1. Fotos diarias de members/stats (lo que muestra la página "Members" de EA).
--    members/stats no trae el playerId: se identifica por gamertag (member_name).
--    Una fila por miembro y día; la última captura del día pisa a las anteriores.
-- -----------------------------------------------------------------------------
create table public.member_snapshots (
  club_id              bigint      not null references public.clubs (club_id) on delete cascade,
  member_name          text        not null,
  snapshot_date        date        not null,
  captured_at          timestamptz not null default now(),
  pro_overall          smallint,
  games_played         integer,
  goals                integer,
  assists              integer,
  win_rate             smallint,
  pass_success_rate    smallint,
  shot_success_rate    smallint,
  tackle_success_rate  smallint,
  passes_made          integer,
  tackles_made         integer,
  clean_sheets_def     integer,
  clean_sheets_gk      integer,
  rating_avg           numeric(4, 2),
  man_of_the_match     integer,
  red_cards            integer,
  favorite_position    text,
  pro_name             text,
  pro_height           smallint,
  raw                  jsonb       not null,
  primary key (club_id, member_name, snapshot_date)
);

create index member_snapshots_name_idx on public.member_snapshots (lower(member_name));

comment on table public.member_snapshots is
  'Foto diaria de members/stats: media del Pro (pro_overall) y totales oficiales de EA desde que el jugador está en el club.';

-- Permite restaurar respaldos con los IDs originales (scripts/restore-sql.ts).
alter table public.persons        alter column person_id set generated by default;
alter table public.collector_runs alter column run_id    set generated by default;

-- -----------------------------------------------------------------------------
-- 2. Fuerza del rival: skillRating del club rival al capturar el partido.
--    Es el valor en el momento de la captura (≈ justo después del partido).
